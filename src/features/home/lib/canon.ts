export interface CanonFilm {
  backdropPath: string | null;
  id: number;
  posterPath: string | null;
  rank: number;
  title: string;
  year: number;
}

export const CANON: readonly CanonFilm[] = ROWS.map(
  ([id, title, year, posterPath, backdropPath], index) => ({
    backdropPath,
    id,
    posterPath,
    rank: index + 1,
    title,
    year,
  }),
);

export const CANON_IDS: readonly number[] = CANON.map((film) => film.id);
